"""
dataset.py - PyTorch Dataset for Speech Emotion Recognition (SER).

Performs audio preprocessing:
  1. Load audio file (via soundfile or torchaudio)
  2. Mono conversion
  3. Resample to target sample rate (default 16 kHz)
  4. Silence trimming at start and end (top_db=30)
  5. Peak/RMS normalization
  6. Fixed-duration crop/pad (4.0 seconds = 64,000 samples)
     - Train: Random crop
     - Val/Test: Center crop
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple, Union

import librosa
import numpy as np
import pandas as pd
import soundfile as sf
import torch
import torchaudio
from torch.utils.data import Dataset

from src.data.augment import AdditiveGaussianNoise, RandomGain

EMOTION_CLASSES = ["neutral", "happy", "angry", "sad", "surprise"]
LABEL_MAP = {cls: idx for idx, cls in enumerate(EMOTION_CLASSES)}


def trim_silence_fast(
    wav: np.ndarray,
    top_db: float = 30.0,
    frame_length: int = 512,
    hop_length: int = 128,
) -> np.ndarray:
    """Fast, vectorized silence trimmer using frame energy."""
    if len(wav) < frame_length:
        return wav
    n_frames = (len(wav) - frame_length) // hop_length + 1
    shape = (n_frames, frame_length)
    strides = (wav.strides[0] * hop_length, wav.strides[0])
    frames = np.lib.stride_tricks.as_strided(wav, shape=shape, strides=strides)
    rms = np.sqrt(np.mean(frames ** 2, axis=1) + 1e-10)
    ref = np.max(rms)
    if ref < 1e-6:
        return wav
    db = 20 * np.log10(rms / ref)
    voiced = np.where(db > -top_db)[0]
    if len(voiced) == 0:
        return wav
    start = voiced[0] * hop_length
    end = min(len(wav), (voiced[-1] + 1) * hop_length + frame_length)
    return wav[start:end]


def load_and_preprocess_wav(
    path: str | Path,
    target_sr: int = 16000,
    crop_samples: int = 64000,  # 4 seconds @ 16kHz
    trim_db: Optional[float] = 30.0,
    normalize: str = "peak",  # 'peak' or 'rms'
    is_train: bool = False,
) -> torch.Tensor:
    """
    Load and preprocess audio waveform.
    Returns: 1D torch.Tensor of shape (crop_samples,) float32 in [-1, 1].
    """
    path_str = str(path)
    try:
        wav_np, orig_sr = sf.read(path_str, dtype="float32", always_2d=False)
    except Exception:
        # Fallback to torchaudio
        wav_t, orig_sr = torchaudio.load(path_str)
        wav_np = wav_t.numpy()

    # Convert to mono if multi-channel
    if wav_np.ndim > 1:
        if wav_np.shape[0] < wav_np.shape[1]:  # channels first
            wav_np = np.mean(wav_np, axis=0)
        else:  # samples first
            wav_np = np.mean(wav_np, axis=1)

    # Resample if needed
    if orig_sr != target_sr:
        wav_np = librosa.resample(wav_np, orig_sr=orig_sr, target_sr=target_sr)

    # Trim silence (top_db=30) at beginning and end
    if trim_db is not None and trim_db > 0 and len(wav_np) > target_sr * 0.2:
        try:
            trimmed = trim_silence_fast(wav_np, top_db=trim_db)
            if len(trimmed) > target_sr * 0.2:
                wav_np = trimmed
        except Exception:
            pass

    # Normalization
    if normalize == "peak":
        peak = np.max(np.abs(wav_np))
        if peak > 1e-6:
            wav_np = (wav_np / peak) * 0.95
    elif normalize == "rms":
        rms = np.sqrt(np.mean(wav_np ** 2))
        if rms > 1e-6:
            wav_np = (wav_np / rms) * 0.1
            wav_np = np.clip(wav_np, -1.0, 1.0)

    # Crop or Pad to target length (crop_samples)
    curr_len = len(wav_np)
    if curr_len < crop_samples:
        # Pad with zeros
        pad_width = crop_samples - curr_len
        if is_train:
            left_pad = np.random.randint(0, pad_width + 1)
        else:
            left_pad = pad_width // 2
        right_pad = pad_width - left_pad
        wav_np = np.pad(wav_np, (left_pad, right_pad), mode="constant", constant_values=0.0)
    elif curr_len > crop_samples:
        # Crop
        if is_train:
            start_idx = np.random.randint(0, curr_len - crop_samples + 1)
        else:
            start_idx = (curr_len - crop_samples) // 2
        wav_np = wav_np[start_idx : start_idx + crop_samples]

    wav_tensor = torch.from_numpy(wav_np.astype(np.float32))
    return wav_tensor


class EmotionDataset(Dataset):
    """
    PyTorch Dataset for Speech Emotion Recognition.
    Reads from train.csv, val.csv, or test.csv generated by make_split.py.
    """
    def __init__(
        self,
        csv_path: str | Path,
        target_sr: int = 16000,
        crop_sec: float = 4.0,
        trim_db: Optional[float] = 30.0,
        normalize: str = "peak",
        split_type: str = "train",  # 'train', 'val', 'test'
        use_augmentation: bool = False,
    ):
        super().__init__()
        self.csv_path = Path(csv_path).resolve()
        if not self.csv_path.exists():
            raise FileNotFoundError(f"Split CSV not found at: {self.csv_path}")

        self.df = pd.read_csv(self.csv_path, dtype={"speaker": str, "utt_id": str})
        self.target_sr = target_sr
        self.crop_samples = int(crop_sec * target_sr)
        self.trim_db = trim_db
        self.normalize = normalize
        self.split_type = split_type.lower()
        self.is_train = self.split_type == "train"

        # Augmentation pipeline (only if is_train and use_augmentation)
        self.use_augmentation = self.is_train and use_augmentation
        if self.use_augmentation:
            self.gain_aug = RandomGain(-4.0, 2.0)
            self.noise_aug = AdditiveGaussianNoise(snr_min=20.0, snr_max=35.0, p=0.4)

    def __len__(self) -> int:
        return len(self.df)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        row = self.df.iloc[idx]
        wav_path = row["path"]

        wav = load_and_preprocess_wav(
            wav_path,
            target_sr=self.target_sr,
            crop_samples=self.crop_samples,
            trim_db=self.trim_db,
            normalize=self.normalize,
            is_train=self.is_train,
        )

        if self.use_augmentation:
            wav = self.gain_aug(wav)
            wav = self.noise_aug(wav)

        label_id = int(row["label_id"]) if "label_id" in row else LABEL_MAP[row["emotion"].lower()]

        return {
            "wav": wav,
            "label": torch.tensor(label_id, dtype=torch.long),
            "speaker": str(row.get("speaker", "")),
            "lang": str(row.get("lang", "")),
            "emotion": str(row.get("emotion", "")),
            "utt_id": str(row.get("utt_id", "")),
            "path": str(wav_path),
        }
